_lock = threading.Lock()


def _fresh_state():
    return {"messages": [], "other_messages": {}, "saved": [], "refuse_sends": False,
            "requested_paths": [], "sent": [], "upload_url_delay": 0.0, "upload_url_times": [],
            "by_client_id": {}, "post_attempts": 0, "book_patches": [],
            # #204 — scripted responses per "METHOD /path" glob, consumed in order; and a switch
            # that makes the whole server unreachable (every non-control request is dropped).
            "scripts": {}, "down": False,
            # #204 — bumped by every reset (each test's setUp). Tokens carry it; see _stale().
            "epoch": 0}


_state = _fresh_state()


# #204 (T7) — every message this stub returns is built from the API's own contract fixture
# (Tests/contract, generated by the API test suite from the running server), so the stub can't
# drift from the real wire shape: a field the server adds or renames shows up here too, and a
# field set here that the server doesn't have is an error.
with open(os.path.join(ROOT, "Tests", "contract", "message_minimal_rest.json")) as _f:
    _MESSAGE_KEYS = list(json.load(_f).keys())


def _dto(**fields):
    unknown = set(fields) - set(_MESSAGE_KEYS)
    if unknown:
        raise KeyError(f"not in the server's MessageDto (Tests/contract): {sorted(unknown)}")
    d = {k: None for k in _MESSAGE_KEYS}
    d.update(is_deleted=False, is_forwarded=False)
    d.update(fields)
    return d


def _access_token():
    """A JWT-shaped token with a real `exp` an hour out (no valid signature — the stub doesn't
    check). The app reads `exp` to decide whether to refresh before handing a send to iOS (#204);
    an opaque token would make it refresh before every send, and a test counting refreshes after
    a 401 would count those too."""
    import base64

    def part(obj):
        return base64.urlsafe_b64encode(json.dumps(obj).encode()).decode().rstrip("=")
    with _lock:
        epoch = _state["epoch"]
    claims = {"sub": USER_ID, "exp": int(time.time()) + 3600, "epoch": epoch}
    return f"{part({'alg': 'HS256', 'typ': 'JWT'})}.{part(claims)}.stub"


def _token_epoch(authorization):
    """The test epoch baked into a request's bearer token, or None."""
    import base64
    try:
        payload = (authorization or "").split(" ", 1)[1].split(".")[1]
        payload += "=" * (-len(payload) % 4)
        return json.loads(base64.urlsafe_b64decode(payload)).get("epoch")
    except (IndexError, ValueError):
        return None


def _now_iso():
    return datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"


